from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = (
    ("email-received-event.schema.json", "emailReceivedEventSchemaJSON"),
    ("sent-email-event.schema.json", "sentEmailEventSchemaJSON"),
)
DEST = ROOT / "schema_generated.go"


def main() -> None:
    declarations = []
    for file_name, var_name in SCHEMAS:
        schema = json.loads((ROOT.parent / "json-schema" / file_name).read_text())
        schema_json = json.dumps(schema, separators=(",", ":"), ensure_ascii=False)
        go_string_literal = json.dumps(schema_json, ensure_ascii=False)
        declarations.append(f"var {var_name} = []byte({go_string_literal})\n")
    output = (
        "package primitive\n\n"
        "// Code generated by scripts/generate_schema_module.py. DO NOT EDIT.\n\n"
        + "\n".join(declarations)
    )
    DEST.write_text(output)


if __name__ == "__main__":
    main()
